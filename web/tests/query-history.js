(async () => {
  const output = document.getElementById('test-result');
  let checks = 0;
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const check = (value, message) => { if (!value) throw new Error(message); checks++; };
  const count = async () => Number(await (await fetch('/counts')).text());
  try {
    await new Promise(resolve => window.addEventListener('load', resolve, { once: true }));
    await wait(50);
    check(htmx.version === '2.0.1', 'HTMX version');
    localStorage.clear();
    const sql = document.getElementById('sql');
    sql.value = 'select manual';
    document.getElementById('run').click();
    await wait(200);
    let entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(entries.length === 1 && entries[0].sql === 'select manual', 'manual request recorded');
    check(await count() === 1, 'manual sends exactly one POST');
    sql.value = 'pending';
    sql.dispatchEvent(new Event('input', { bubbles: true }));
    document.querySelector('#query-history-list button').click();
    await wait(700);
    entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(entries.length === 1 && sql.value === 'select manual', 'load cancels delayed request');
    check(await count() === 1, 'load cancels pending POST');
    sql.value = 'select auto';
    sql.dispatchEvent(new Event('input', { bubbles: true }));
    await wait(700);
    entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(entries.length === 2 && entries[0].sql === 'select auto', 'new input runs and records');
    check(await count() === 2, 'subsequent input sends one POST');
    sql.value = 'pending removal';
    sql.dispatchEvent(new Event('input', { bubbles: true }));
    document.querySelector('#query-history-list button[aria-label^="Remove"]').click();
    await wait(700);
    check(await count() === 2, 'remove cancels pending POST');
    sql.value = 'pending clear';
    sql.dispatchEvent(new Event('input', { bubbles: true }));
    document.getElementById('query-history-clear').click();
    await wait(700);
    check(await count() === 2, 'clear cancels pending POST');
    sql.value = 'after clear';
    sql.dispatchEvent(new Event('input', { bubbles: true }));
    await wait(700);
    check(await count() === 3, 'genuine input after clear sends one POST');
    sql.value = '   ';
    document.getElementById('run').click();
    await wait(200);
    entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(await count() === 4 && entries.length === 1, 'whitespace POST does not create an entry');
    sql.value = 'missing identity';
    document.getElementById('run').click();
    await wait(200);
    entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(await count() === 5 && entries.length === 1, 'missing identity is not guessed or retried');
    sql.value = 'SQL error';
    document.getElementById('run').click();
    await wait(200);
    entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(await count() === 6 && entries[0].sql === 'SQL error', 'error response with identity records SQL');
    const payloads = await (await fetch('/payloads')).json();
    check(JSON.stringify(payloads) === JSON.stringify(['select manual', 'select auto', 'after clear', '   ', 'missing identity', 'SQL error']), 'exact SQL payloads and no extra requests');
    sql.value = 'invalid identity';
    document.getElementById('run').click();
    await wait(200);
    entries = JSON.parse(localStorage.getItem('query-history:v1:' + 'a'.repeat(64)));
    check(entries.length === 2 && await count() === 7, 'invalid identity is not recorded or retried');
    const key = 'query-history:v1:' + 'a'.repeat(64);
    document.getElementById('query-history-clear').click();
    const run = document.getElementById('run');
    for (let i = 0; i < 51; i++) {
      sql.value = i === 49 || i === 50 ? 'duplicate' : `query ${i}`;
      const finished = new Promise(resolve => document.body.addEventListener('htmx:afterRequest', resolve, { once: true }));
      run.click();
      await finished;
    }
    entries = JSON.parse(localStorage.getItem(key));
    check(entries.length === 50 && entries[0].sql === 'duplicate' && entries[1].sql === 'duplicate' && !entries.some(e => e.sql === 'query 0'), '51 submissions keep newest 50 and duplicates');
    check(entries.every(e => Object.keys(e).sort().join(',') === 'sql,timestamp'), 'history contains only SQL and timestamp');
    document.querySelector('#query-history-list button[aria-label^="Remove"]').click();
    entries = JSON.parse(localStorage.getItem(key));
    check(entries.length === 49 && entries.filter(e => e.sql === 'duplicate').length === 1, 'remove deletes one duplicate');
    const literal = '<img src=x onerror="window.historyXSS=1">\n長い SQL';
    sql.value = literal;
    const finished = new Promise(resolve => document.body.addEventListener('htmx:afterRequest', resolve, { once: true }));
    run.click(); await finished;
    check(!window.historyXSS && !document.querySelector('#query-history-list img') && document.querySelector('#query-history-list button').textContent.includes(literal), 'multiline Unicode SQL rendered literally');
    check(document.querySelector('#query-history-list time').dateTime && document.querySelector('#query-history-list time').textContent, 'readable timestamp');
    const beforeLiteralLoad = await count();
    sql.value = '';
    document.querySelector('#query-history-list button').click();
    await wait(700);
    check(sql.value === literal && await count() === beforeLiteralLoad, 'full multiline SQL loads without a POST');
    localStorage.setItem(key, '{bad');
    sql.value = 'after malformed';
    const malformedFinished = new Promise(resolve => document.body.addEventListener('htmx:afterRequest', resolve, { once: true }));
    run.click(); await malformedFinished;
    entries = JSON.parse(localStorage.getItem(key));
    check(entries.length === 1 && entries[0].sql === 'after malformed', 'malformed storage does not block query');
    document.getElementById('query-history-clear').click();
    const otherKey = 'query-history:v1:' + 'b'.repeat(64);
    localStorage.removeItem(otherKey);
    const raceButtons = ['race A', 'race B'].map((value, index) => {
      const input = document.createElement('input');
      input.id = `race-input-${index}`; input.name = 'sql'; input.value = value;
      const button = document.createElement('button');
      button.setAttribute('hx-post', '/v1/api/query');
      button.setAttribute('hx-include', `#${input.id}`);
      button.setAttribute('hx-target', '#query-results');
      document.body.append(input, button); htmx.process(button);
      return button;
    });
    raceButtons[0].click(); await wait(50); raceButtons[1].click(); await wait(600);
    check(JSON.parse(localStorage.getItem(key))[0].sql === 'race A' && JSON.parse(localStorage.getItem(otherKey))[0].sql === 'race B', 'reversed responses retain their own SQL and effective identity');
    raceButtons[0].click(); await wait(50);
    document.getElementById('query-history-clear').click();
    await wait(600);
    check(JSON.parse(localStorage.getItem(key)).length === 1 && JSON.parse(localStorage.getItem(otherKey)).length === 1, 'pending response adds after clear without clearing another connection');
    document.getElementById('query-history-clear').click();
    document.getElementById('race-input-1').value = 'race same connection';
    raceButtons[0].click(); await wait(50); raceButtons[1].click(); await wait(600);
    entries = JSON.parse(localStorage.getItem(key));
    check(entries.length === 2 && entries[0].sql === 'race same connection' && entries[1].sql === 'race A', 'same-identity reversed responses retain submission order');
    const storageSet = Storage.prototype.setItem;
    Storage.prototype.setItem = function () { throw new Error('synthetic quota failure'); };
    const beforeFailure = await count();
    sql.value = 'query with storage failure';
    const storageFinished = new Promise(resolve => document.body.addEventListener('htmx:afterRequest', resolve, { once: true }));
    run.click(); await storageFinished;
    Storage.prototype.setItem = storageSet;
    check(await count() === beforeFailure + 1, 'storage write failure does not block query POST');
    const storageDescriptor = Object.getOwnPropertyDescriptor(window, 'localStorage');
    Object.defineProperty(window, 'localStorage', { configurable: true, get() { throw new Error('synthetic blocked storage'); } });
    const beforeBlocked = await count();
    sql.value = 'query with blocked storage';
    const blockedFinished = new Promise(resolve => document.body.addEventListener('htmx:afterRequest', resolve, { once: true }));
    run.click(); await blockedFinished;
    Object.defineProperty(window, 'localStorage', storageDescriptor);
    check(await count() === beforeBlocked + 1, 'throwing storage getter does not block query POST');
    window.dispatchEvent(new StorageEvent('storage', { key }));
    for (const action of ['load', 'remove']) {
      const before = await count();
      sql.value = 'pending ' + action;
      sql.dispatchEvent(new Event('input', { bubbles: true }));
      const selector = action === 'load' ? '#query-history-list button' : '#query-history-list button[aria-label^="Remove"]';
      document.querySelector(selector).click();
      await wait(700);
      check(await count() === before, action + ' suppresses pending POST');
      sql.value = 'genuine input after ' + action;
      sql.dispatchEvent(new Event('input', { bubbles: true }));
      await wait(700);
      check(await count() === before + 1, 'genuine input after ' + action + ' sends one POST');
    }
    output.textContent = `PASS ${checks} assertions`;
  } catch (error) { output.textContent = `FAIL ${checks} assertions: ${error.stack}`; }
  await fetch('/done', { method: 'POST', body: output.textContent });
})();
